"""Pure output generation and atomic file replacement."""

import hashlib
import os
import tempfile
from pathlib import Path

import yaml

from .model import RegistryOperation


def compliant_expression(op: RegistryOperation, variable: str) -> str:
    checks = [
        f"({variable}.exists | default(false))",
        f"({variable}.type | default('')) == 'REG_DWORD'",
    ]
    if op.minimum is not None:
        checks.append(f"({variable}.value | default(0) | int) >= {op.minimum}")
    if op.maximum is not None:
        checks.append(f"({variable}.value | default(0) | int) <= {op.maximum}")
    return " and ".join(checks)


def playbook(operations: list[RegistryOperation]) -> str:
    tasks = []
    for op in operations:
        rules = ", ".join(sorted({o.rule for o in op.origins}))
        write = {
            "name": f"{rules}: set {op.path} / {op.name or '(Default)'}",
            "ansible.windows.win_regedit": {
                "path": op.path,
                "name": op.name,
                "type": op.type,
                "data": op.value,
                "state": "present",
            },
        }
        if op.minimum is not None or op.maximum is not None:
            token = hashlib.sha256((op.key[0] + "\0" + op.key[1]).encode()).hexdigest()[:16]
            variable = "scapolite_registry_" + token
            tasks.append(
                {
                    "name": f"{rules}: read constrained value",
                    "ansible.windows.win_reg_stat": {"path": op.path, "name": op.name},
                    "register": variable,
                }
            )
            write["when"] = "not (" + compliant_expression(op, variable) + ")"
        tasks.append(write)
    output = [
        {
            "name": "Apply selected Scapolite registry rules",
            "hosts": "windows",
            "gather_facts": False,
            "any_errors_fatal": True,
            "tasks": tasks,
        }
    ]
    return "# Generated by scapolite-ansible.\n" + yaml.safe_dump(
        output, sort_keys=False, allow_unicode=True, width=110
    )


def atomic_write(path: Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    temporary = None
    try:
        with tempfile.NamedTemporaryFile(
            mode="w",
            encoding="utf-8",
            newline="\n",
            dir=path.parent,
            prefix=".scapolite-",
            suffix=".tmp",
            delete=False,
        ) as stream:
            temporary = Path(stream.name)
            stream.write(text)
            stream.flush()
            os.fsync(stream.fileno())
        os.replace(temporary, path)
    finally:
        if temporary is not None and temporary.exists():
            temporary.unlink()
